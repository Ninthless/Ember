type GlyphProps = SVGProps<SVGSVGElement> & {
  weight?: IconWeight
  size?: string | number
  weights?: Weights
}

type Props = {
  name: IconName
  filled?: boolean
  className?: string
}

const Glyph = forwardRef<SVGSVGElement, GlyphProps>(function Glyph(
  { weight = "regular", size = "1em", weights, children, ...props },
  ref
) {
  return (
    <svg ref={ref} xmlns="http://www.w3.org/2000/svg" width={size} height={size} fill="currentColor" viewBox="0 0 256 256" {...props}>
      {children}
      {weights?.get(weight)}
    </svg>
  )
})

function mark(weights: Weights): ComponentType<GlyphProps> {
  const Icon = forwardRef<SVGSVGElement, GlyphProps>(function Icon(props, ref) {
    return <Glyph ref={ref} weights={weights} {...props} />
  })
  return Icon
}

